; ============= 阶乘计算（查表法）=============
; 功能：通过预存查找表直接获取n!的结果
; 查找表存储在A0H~A5H，分别对应0!~5!
; 输入n存放在80H，结果存放在81H
; 优点：时间复杂度O(1)，无需循环计算
; ============= 查找表初始化 =============
MOV A, #01H     ; 0! = 1
MOV A0H, A      ; 存入A0H
MOV A, #01H     ; 1! = 1
MOV A1H, A      ; 存入A1H
MOV A, #02H     ; 2! = 2
MOV A2H, A      ; 存入A2H
MOV A, #06H     ; 3! = 6
MOV A3H, A      ; 存入A3H
MOV A, #18H     ; 4! = 24 (0x18)
MOV A4H, A      ; 存入A4H
MOV A, #78H     ; 5! = 120 (0x78)
MOV A5H, A      ; 存入A5H
; ============= 输入与查表模块 =============
MOV A, #05H     ; 输入n=5（可修改为0~5）
MOV 80H, A      ; 存入80H

MOV A, 80H      ; 读取n值
MOV R0, A       ; R0=n（用作查找表索引）
MOV A, R0       ; 计算查找表地址
ADD A, #A0H     ; 地址=A0H+n
MOV R1, A       ; R1=查找表地址
MOV A, @R1      ; 读取查找表中的n!值
MOV 81H, A      ; 结果存入81H
; ============= 结束 =============
DONE:
    NOP
    JMP DONE    ; 死循环结束程序
