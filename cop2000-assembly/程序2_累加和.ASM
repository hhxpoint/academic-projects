;=========================================================
; 程序2: 求 1+2+3+4+5+6+7+8 = 36 = 0x24
;---------------------------------------------------------
; 算法: 单层循环, 计数器 R0 从 8 递减到 0
;   每次把 R0 的当前值累加到 R1
; 寄存器分配:
;   R0 = 计数器 (8→0, 兼做加数)
;   R1 = 累加和 (0→36)
;   A  = 运算中转
;=========================================================

        ORG  00H
        MOV  A, #00H
        MOV  R1, A          ; R1 = sum = 0
        MOV  A, #08H
        MOV  R0, A          ; R0 = 8 (计数)

LOOP:   MOV  A, R1          ; A = sum
        ADD  A, R0          ; A = sum + R0
        MOV  R1, A          ; sum 更新

        MOV  A, R0          ; R0--
        SUB  A, #01H
        MOV  R0, A

        JZ   DONE           ; R0==0 结束
        JMP  LOOP

DONE:   MOV  A, R1          ; A = sum = 36 = 0x24
                        ; 输出 0x24
HALT:   JMP  HALT
        END
