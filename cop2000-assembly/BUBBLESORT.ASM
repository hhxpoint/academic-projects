; ============= 冒泡排序模块 =============
MOV R0, #80H    ; 初始化外循环上边界（数组起始地址）
MOV R1, #89H    ; 初始化外循环下边界（数组结束地址）
LOOP1:          ; 外循环开始
    MOV A, R1    ; 将外循环下边界地址存入累加器A
    SUB A, R0    ; 计算R1 - R0
    JZ LOOPRE    ; 如果结果为0（R1=R0），表示排序完成，跳转到补码转换部分

    MOV A, R0    ; 将外循环上边界地址存入累加器A
    MOV R2, A    ; 初始化内循环指针R2为外循环上边界
    ADD A, #01H  ; R2指针加1
    MOV R3, A    ; 初始化内循环指针R3为R2的下一个位置
LOOP2:          ; 内循环开始
    MOV A, R1    ; 将外循环下边界地址存入累加器A
    SUB A, R2    ; 计算R1 - R2
    JZ LOOP11    ; 如果结果为0（R2=R1），表示内循环完成，跳转到外循环尾部

    MOV A, @R3   ; 取R3指向的移码值
    SUB A, @R2   ; 比较R3和R2指向的移码值
    JC LOOP3     ; 如果R3的值 < R2的值（借位标志CF=1），跳转到交换部分
LOOP22:         ; 内循环尾部
    ADD R2, #01H ; R2指针加1
    ADD R3, #01H ; R3指针加1
    JMP LOOP2    ; 继续内循环
LOOP11:         ; 外循环尾部
    SUB R1, #01H ; 外循环下边界减1
    JMP LOOP1    ; 继续外循环
LOOP3:          ; 交换部分
    MOV A, @R2   ; 取R2指向的值
    MOV 90H, A   ; 暂存到内存地址90H
    MOV A, @R3   ; 取R3指向的值
    MOV @R2, A   ; 将R3的值赋给R2指向的位置
    MOV A, 90H   ; 从暂存处取回原值
    MOV @R3, A   ; 将原值赋给R3指向的位置
    JMP LOOP22   ; 返回内循环尾部
; ============= 补码还原模块 =============
LOOPRE:         ; 转换补码部分
    MOV R0, #80H ; 初始化循环上边界（原移码数组起始地址）
    MOV R1, #89H ; 初始化循环下边界（原移码数组结束地址）
LOOP4:          ; 转码循环开始
    MOV A, R1    ; 将当前处理的地址存入累加器A
    ADD A, #10H  ; 计算目标地址（原地址+16）
    MOV R2, A    ; 将目标地址存入R2

    MOV A, @R1   ; 取当前地址的移码值
    SUB A, #80H  ; 移码转回补码（移码 - 128 = 补码）
    MOV @R2, A   ; 将补码存入目标地址（90H~99H）

    MOV A, R1    ; 将当前地址存入累加器A
    SUB A, R0    ; 计算R1 - R0
    JZ LOOPEND   ; 如果结果为0（R1=R0），表示所有数据都已转换，跳转到结束
    SUB R1, #01H ; 当前地址减1
    JMP LOOP4    ; 继续转换下一个数据
LOOPEND:        ; 排序完成
    NOP
    JMP LOOPEND  ; 加入死循环结束程序


