; ============= 初始化与边界处理模块 =============
    MOV A, 80H          ; 将待判断的数字 N 从主存 80H 读入累加器 A
    MOV R0, A           ; 将 N 备份到寄存器 R0 中

    ; 边界检查 1：判断 N 是否 < 2
    SUB A, #02H         ; A = N - 2
    JC NOT_PRIME        ; 如果产生借位，说明 N < 2 (即0或1)，跳至非质数分支

    ; 边界检查 2：判断 N 是否 == 2
    JZ IS_PRIME         ; 如果结果为 0，说明 N == 2，跳至质数分支

    ; 对于 N > 2 的情况，初始化除数 i
    MOV R1, #02H        ; R1 作为除数寄存器，从 2 开始

; ============= 外层循环：递增除数 i =============
OUTER_LOOP:
    MOV A, R0           ; 读入原数 N
    SUB A, R1           ; 比较 N 和当前的除数 i
    JZ IS_PRIME         ; 如果 N == i，说明 2 到 N-1 都不能整除它，判定为质数！

    MOV A, R0           ; 重新将 N 装入 A
    MOV R2, A           ; R2 作为模拟取模时的"余数暂存器"，初始化为 N

; ============= 内层循环：连续减法模拟取模 N % i =============
MOD_LOOP:
    MOV A, R2           ; 读入当前剩余的数
    SUB A, R1           ; 减去当前的除数 i
    JZ NOT_PRIME        ; 若减法结果刚好为 0 (整除)，判定为非质数！
    JC NEXT_I           ; 若不够减了(产生借位)，说明有不为0的余数，当前 i 无法整除 N

    MOV R2, A           ; 够减且不为0，将减后的新余数存回 R2
    JMP MOD_LOOP        ; 继续连减

; ============= 步进处理 =============
NEXT_I:
    MOV A, R1           ; 将除数 i 送入 A
    ADD A, #01H         ; 除数 i 加 1
    MOV R1, A           ; 存回 R1 寄存器
    JMP OUTER_LOOP      ; 跳转回外层循环进行下一轮试除

; ============= 结果输出模块 =============
NOT_PRIME:
    MOV A, #00H         ; 若非质数，输出标志 00H
    MOV 81H, A          ; 写入主存 81H
    JMP END_PROG        ; 跳转至结束

IS_PRIME:
    MOV A, #01H         ; 若为质数，输出标志 01H
    MOV 81H, A          ; 写入主存 81H

; ============= 程序停机 =============
END_PROG:
    NOP
    JMP END_PROG        ; 死循环锁死程序状态，防止PC跑飞
